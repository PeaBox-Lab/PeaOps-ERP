"""Shared PDF document builder used by invoice, quote, sales order and purchase order endpoints."""
from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer

def build_document(company_name: str, company_code: str, company_currency: str, party_name: str, party_code: str, party_gstin: str | None, doc_number: str, document_type: str, issue_date, due_date, status: str, lines: list[dict], totals: list[tuple], footer_extra: list[str] | None = None, party_label: str = "Bill To"):
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, rightMargin=18*mm, leftMargin=18*mm, topMargin=18*mm, bottomMargin=18*mm)
    styles = getSampleStyleSheet()
    normal = styles['Normal']
    body = []
    header = Table([
        [Paragraph(f"<b>{company_name}</b>", styles['Title']),
         Paragraph(f"<b>{document_type.upper()}</b><br/><b>{doc_number}</b>", styles['Heading2'])],
        [Paragraph(f"{company_code} &nbsp;•&nbsp; {company_currency}", normal),
         Paragraph(f"{issue_date} &nbsp;•&nbsp; Due: {due_date}", normal)],
    ], colWidths=[90*mm, 90*mm])
    header.setStyle(TableStyle([('VALIGN',(0,0),(-1,-1),'MIDDLE'),('BOTTOMPADDING',(0,0),(-1,-1),6)]))
    body.append(header)
    body.append(Spacer(1, 6))
    party_tbl = Table([
        [Paragraph(f'<b>{party_label}</b>', styles['Heading3'])],
        [Paragraph(f"{party_name} ({party_code})" if party_name else 'Unknown party', normal)],
        [Paragraph(f"GSTIN: {party_gstin if party_gstin else '—'}", normal)],
    ], colWidths=[180*mm])
    party_tbl.setStyle(TableStyle([('BOTTOMPADDING',(0,0),(-1,-1),2)]))
    body.append(party_tbl)
    body.append(Spacer(1, 6))
    headers = ['#', 'Description', 'Qty', 'Unit Price', 'Tax %', 'Net']
    rows = [headers] + lines
    for _, _, _, _, _, _ in rows[1:]:
        pass
    rows.append(['', Paragraph('<b>Totals</b>', normal), '', '', '', ''])
    for label, value in totals:
        rows.append(['', '', '', Paragraph(f"<b>{label}</b>" if label.lower() in {'total','grand total'} else label, normal), '', f"{value:.2f}" if isinstance(value, (int, float)) else str(value)])
    tbl = Table(rows, colWidths=[10*mm, 70*mm, 20*mm, 25*mm, 20*mm, 35*mm])
    tbl.setStyle(TableStyle([
        ('BACKGROUND',(0,0),(-1,0),colors.HexColor('#f0f4f8')),
        ('GRID',(0,0),(-1,0),0.5,colors.HexColor('#dde3ea')),
        ('FONTNAME',(0,0),(-1,0),'Helvetica-Bold'),
        ('FONTNAME',(0,-len(totals)-1),(-1,-1),'Helvetica-Bold'),
        ('LINEABOVE',(0,-len(totals)-1),(-1,-len(totals)-1),0.5,colors.HexColor('#a0aec0')),
        ('LINEBELOW',(0,-1),(-1,-1),1,colors.HexColor('#4a5568')),
        ('VALIGN',(0,0),(-1,-1),'MIDDLE'),
        ('PADDING',(0,0),(-1,-1),4),
    ]))
    body.append(tbl)
    body.append(Spacer(1, 10))
    if footer_extra:
        for line in footer_extra:
            body.append(Paragraph(line, normal))
    body.append(Paragraph(f"Status: {status}", normal))
    body.append(Paragraph("Generated by PeaOps ERP", styles['Italic']))
    doc.build(body)
    buf.seek(0)
    return buf